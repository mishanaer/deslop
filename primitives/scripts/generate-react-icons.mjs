import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const check = process.argv.includes("--check");
const root = fileURLToPath(new URL("../", import.meta.url));
const iconDirectory = `${root}/icons`;
const jsPath = `${root}/icons-react.js`;
const typesPath = `${root}/icons-react.d.ts`;

const files = (await readdir(iconDirectory))
  .filter((file) => file.endsWith(".svg"))
  .sort();

const toComponentName = (name) =>
  `Icon${name
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")}`;

const records = [];
const componentNames = new Set();

for (const file of files) {
  const name = file.slice(0, -4);
  const svg = await readFile(`${iconDirectory}/${file}`, "utf8");
  const match = svg.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>\s*$/);

  if (!match) throw new Error(`Could not read root SVG element from ${file}`);
  if (/<(?:script|foreignObject)\b|\son[a-z]+\s*=/i.test(match[1])) {
    throw new Error(`${file} contains markup that cannot be embedded safely`);
  }

  const componentName = toComponentName(name);
  if (componentNames.has(componentName)) {
    throw new Error(`Duplicate React component name: ${componentName}`);
  }
  componentNames.add(componentName);

  records.push({ name, componentName, markup: match[1].trim() });
}

const iconNames = records.map(({ name }) => JSON.stringify(name)).join(",\n  ");
const iconMarkup = records
  .map(({ name, markup }) => `  ${JSON.stringify(name)}: ${JSON.stringify(markup)}`)
  .join(",\n");
const componentExports = records
  .map(
    ({ markup, componentName }) =>
      `export const ${componentName} = /* @__PURE__ */ createIcon(${JSON.stringify(markup)}, ${JSON.stringify(componentName)});`,
  )
  .join("\n");
const componentMap = records
  .map(({ name, componentName }) => `  ${JSON.stringify(name)}: ${componentName}`)
  .join(",\n");

const js = `// Generated by scripts/generate-react-icons.mjs. Do not edit manually.
import { createElement, forwardRef } from "react";

export const iconNames = /* @__PURE__ */ Object.freeze([
  ${iconNames}
]);

const iconMarkup = /* @__PURE__ */ Object.freeze({
${iconMarkup}
});

function renderIcon(markup, { size = 24, title, ...props }, ref) {
  const labelled = Boolean(title || props["aria-label"] || props["aria-labelledby"]);

  return createElement(
    "svg",
    {
      xmlns: "http://www.w3.org/2000/svg",
      viewBox: "0 0 24 24",
      width: size,
      height: size,
      fill: "none",
      focusable: "false",
      role: labelled ? "img" : undefined,
      "aria-hidden": labelled ? undefined : true,
      ...props,
      ref,
    },
    title ? createElement("title", null, title) : null,
    createElement("g", { dangerouslySetInnerHTML: { __html: markup } })
  );
}

export const Icon = /* @__PURE__ */ forwardRef(function DeslopIcon(
  { name, ...props },
  ref
) {
  const markup = iconMarkup[name];
  return markup ? renderIcon(markup, props, ref) : null;
});
Icon.displayName = "Icon";

function createIcon(markup, displayName) {
  const Component = forwardRef(function DeslopNamedIcon(props, ref) {
    return renderIcon(markup, props, ref);
  });
  Component.displayName = displayName;
  return Component;
}

${componentExports}

export const iconComponents = /* @__PURE__ */ Object.freeze({
${componentMap}
});

export const getIconComponent = (name) => iconComponents[name];
`;

const componentDeclarations = records
  .map(({ componentName }) => `export const ${componentName}: IconComponent;`)
  .join("\n");

const types = `// Generated by scripts/generate-react-icons.mjs. Do not edit manually.
import type { ForwardRefExoticComponent, RefAttributes, SVGProps } from "react";

export const iconNames: readonly [
  ${iconNames}
];

export type IconName = (typeof iconNames)[number];
export type IconBaseProps = Omit<SVGProps<SVGSVGElement>, "children" | "name"> & {
  size?: number | string;
  title?: string;
};
export type IconProps = IconBaseProps & { name: IconName };
export type IconComponent = ForwardRefExoticComponent<
  IconBaseProps & RefAttributes<SVGSVGElement>
>;

export const Icon: ForwardRefExoticComponent<
  IconProps & RefAttributes<SVGSVGElement>
>;

${componentDeclarations}

export const iconComponents: Readonly<Record<IconName, IconComponent>>;
export function getIconComponent(name: IconName): IconComponent;
export function getIconComponent(name: string): IconComponent | undefined;
`;

async function verify(path, expected) {
  let actual = "";
  try {
    actual = await readFile(path, "utf8");
  } catch {
    // Report the same actionable error for a missing or stale generated file.
  }

  if (actual !== expected) {
    throw new Error(`${path} is stale; run npm run icons:react:generate`);
  }
}

if (check) {
  await verify(jsPath, js);
  await verify(typesPath, types);
  console.log(`${records.length} React icon components are up to date.`);
} else {
  await writeFile(jsPath, js);
  await writeFile(typesPath, types);
  console.log(`Generated ${records.length} React icon components.`);
}

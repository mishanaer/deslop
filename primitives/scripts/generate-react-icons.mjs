// The source export uses only paths, groups and clipping definitions. Reject
// unexpected markup instead of injecting SVG strings into the DOM.
function parseSvg(source, path) {
  const stack = [];
  let rootNode;
  const tokens = source.trim().match(/<[^>]+>/g) ?? [];
  if (tokens.join("") !== source.trim()) throw new Error(`Unexpected SVG content: ${path}`);
  for (const token of tokens) {
    const closing = /^<\//.test(token);
    const tag = token.match(/^<\/?([\w]+)/)?.[1];
    if (!allowedTags.has(tag)) throw new Error(`Unsupported SVG element in ${path}: ${tag}`);
    if (closing) {
      if (stack.pop()?.[0] !== tag) throw new Error(`Unbalanced SVG in ${path}`);
      continue;
    }
    const attributes = {};
    const rawAttributes = token.slice(tag.length + 1).replace(/\/?\s*>$/, "");
    const attributePattern = /([\w-]+)="([^"]*)"/g;
    if (rawAttributes.replace(attributePattern, "").trim()) throw new Error(`Invalid SVG attributes: ${path}`);
    for (const [, key, value] of rawAttributes.matchAll(attributePattern)) {
      if (!allowedAttributes.has(key)) throw new Error(`Unsupported SVG attribute: ${key} in ${path}`);
      attributes[reactAttributes[key] ?? key] = value;
    }
    const node = [tag, attributes, []];
    if (stack.length) stack.at(-1)[2].push(node);
    else if (rootNode) throw new Error(`Multiple roots in ${path}`);
    else rootNode = node;
    if (!/\/>$/.test(token)) stack.push(node);
  }
  if (stack.length || rootNode?.[0] !== "svg" || rootNode[1].viewBox !== "0 0 24 24") {
    throw new Error(`Invalid SVG root: ${path}`);
  }
  return rootNode[2];
}

